use crate::Result;
use std::{collections::BTreeMap, fs, path::Path};
use ts_rs::{Config, TS, TypeVisitor};

struct Declarations {
    config: Config,
    types: BTreeMap<String, String>,
}
impl TypeVisitor for Declarations {
    fn visit<T: TS + 'static + ?Sized>(&mut self) {
        if T::output_path().is_none() {
            return;
        }
        let name = T::ident(&self.config);
        if self.types.contains_key(&name) {
            return;
        }
        self.types
            .insert(name, format!("export {}\n", T::decl(&self.config)));
        T::visit_dependencies(self);
    }
}

pub fn run(root: &Path, check: bool) -> Result<()> {
    let mut declarations = Declarations {
        config: Config::default().with_large_int("number"),
        types: BTreeMap::new(),
    };
    declarations.visit::<tiechui_protocol::PluginProtocol>();
    declarations.visit::<tiechui_protocol::ApprovalDecision>();
    declarations.visit::<tiechui_protocol::ProgramRun>();
    let generated = format!(
        "// Generated by cargo run -p xtask -- typescript. Do not edit.\n\n{}",
        declarations
            .types
            .into_values()
            .collect::<Vec<_>>()
            .join("\n")
    );
    let path = root.join("sdk/typescript/protocol.ts");
    if check {
        if fs::read_to_string(&path).ok().as_deref() != Some(&generated) {
            return Err(
                "sdk/typescript/protocol.ts is stale; run cargo run -p xtask -- typescript".into(),
            );
        }
        println!("TypeScript protocol types are current");
    } else {
        fs::create_dir_all(path.parent().ok_or("Missing SDK directory")?)?;
        fs::write(path, generated)?;
    }
    Ok(())
}

#[cfg(test)]
#[allow(clippy::unwrap_used)]
mod tests {
    use super::*;
    #[test]
    fn detects_missing_and_changed_types_without_writing() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../target/typescript-tests");
        fs::create_dir_all(&root).unwrap();
        let temp = tempfile::tempdir_in(root).unwrap();
        assert!(run(temp.path(), true).is_err());
        run(temp.path(), false).unwrap();
        run(temp.path(), true).unwrap();
        let path = temp.path().join("sdk/typescript/protocol.ts");
        let generated = fs::read_to_string(&path).unwrap();
        assert!(generated.contains("PluginRequest"));
        assert!(!generated.contains("bigint"));
        fs::write(&path, "stale").unwrap();
        assert!(run(temp.path(), true).is_err());
        assert_eq!(fs::read_to_string(path).unwrap(), "stale");
    }
}

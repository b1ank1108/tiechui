#!/usr/bin/env python3
"""Regenerate site/snapshots.js from the TUI insta snapshots. Python 3.9+, stdlib only."""
import json
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "crates/tiechui-tui/tests/snapshots"
TARGET = ROOT / "site/snapshots.js"

TAG = re.compile(r"\[(-|[bdius]|fg|bg)")
# Plain snapshots only mark sections with these; styled ones start every content line with a tag.
PLAIN_HEADER = re.compile(r"== .+|\d+x\d+( light=(true|false))?")


def git(*args):
    return subprocess.run(["git", *args], cwd=ROOT, capture_output=True, text=True, check=True).stdout.strip()


def variant(text, inherited):
    cols, light = inherited
    size = re.match(r"(?:menu |permissions )?(\d+)(?:x\d+)?\b", text)
    if size:
        cols = int(size.group(1))
    if re.search(r"light=false|/ dark\b", text):
        light = False
    elif re.search(r"light=true|/ light\b", text):
        light = True
    return cols, light


def parse(path):
    _, meta, body = path.read_text(encoding="utf-8").split("---\n", 2)
    lines = body.rstrip("\n").split("\n")
    expression = re.search(r"fixture\(ColorLevel::(\w+), (true|false)\)(?:, (\d+))?", meta)
    level = expression.group(1) if expression else "TrueColor"
    cols = int(expression.group(3)) if expression and expression.group(3) else None
    light = expression.group(2) == "true" if expression else "light" in path.stem
    for size in re.findall(r"_(\d+)(?:_|$)", path.stem):
        cols = int(size)
    styled = any(TAG.match(line) for line in lines)

    def header(line):
        if PLAIN_HEADER.fullmatch(line):
            return True
        return styled and line != "" and not TAG.match(line) and not line.startswith("[cursor ")

    parts, current = [], {"title": "", "cols": cols, "light": light, "lines": []}
    for line in lines:
        if header(line):
            if current["title"] or any(current["lines"]):
                parts.append(current)
            cols, light = variant(line, (current["cols"], current["light"]))
            current = {"title": line, "cols": cols, "light": light, "lines": []}
        else:
            current["lines"].append(line)
    parts.append(current)
    # Leading blank rows stay: recorded cursor rows count from the first line after a header.
    for part in parts:
        while part["lines"] and part["lines"][-1] == "":
            part["lines"].pop()
    return {"level": level, "styled": styled, "parts": parts}


def main():
    snapshots = {path.stem: parse(path) for path in sorted(SOURCE.glob("*.snap"))}
    relative = SOURCE.relative_to(ROOT).as_posix()
    commit = git("log", "-1", "--format=%h %cs", "--", relative).split()
    if git("status", "--porcelain", "--", relative):
        commit[0] += "+dirty"
    data = {"commit": commit[0], "date": commit[1], "snapshots": snapshots}
    TARGET.write_text(
        "// Generated by scripts/ui_gallery.py from " + relative + ". Do not edit.\n"
        "window.TC_GALLERY = " + json.dumps(data, ensure_ascii=False, indent=1) + ";\n",
        encoding="utf-8",
    )
    print(f"{TARGET.relative_to(ROOT)}: {len(snapshots)} snapshots at {commit[0]}")


if __name__ == "__main__":
    main()
